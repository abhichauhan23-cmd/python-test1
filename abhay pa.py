def calculate_volume_shocks(df, threshold_percent=0.10):
    """
    Identifies 'volume shocks' based on daily percentage change in volume.

    Args:
        df (pandas.DataFrame): The input DataFrame with a 'Volume' column.
        threshold_percent (float): The percentage threshold for a volume shock (e.g., 0.10 for 10%).

    Returns:
        pandas.DataFrame: The DataFrame with an added 'Volume_Shock' binary column.
    """
    # Calculate daily percentage change in Volume
    df['Volume_Pct_Change'] = df['Volume'].pct_change()

    # Identify volume shocks
    df['Volume_Shock'] = ((df['Volume_Pct_Change'].abs() >= threshold_percent)).astype(int)

    return df

