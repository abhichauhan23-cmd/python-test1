from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import GridSearchCV
import numpy as np

def mean_absolute_percentage_error(y_true, y_pred):
    """
    Calculates the Mean Absolute Percentage Error (MAPE).
    Handles cases where y_true might contain zeros.
    """
    # Avoid division by zero by replacing zeros in y_true with NaN, then filtering
    y_true, y_pred = np.array(y_true), np.array(y_pred)
    # Replace 0s in y_true with a very small number to avoid division by zero
    # or handle them by excluding those points if y_true is exactly 0
    # For this exercise, let's assume y_true won't be exactly zero for stock prices,
    # or we handle it by returning a large error for those points if it occurs.
    # A common approach is to exclude points where y_true is zero, but here we add a small epsilon.
    epsilon = np.finfo(np.float64).eps # Smallest representable positive number
    return np.mean(np.abs((y_true - y_pred) / np.maximum(np.abs(y_true), epsilon))) * 100

