"""## Combine Price and Volume Shock Features

### Subtask:
Create combined shock features for each DataFrame. This involves generating two new binary columns for each stock/index:
1. `Any_Shock`: 1 if either a `Price_Shock` or a `Volume_Shock` occurred on that day, 0 otherwise.
2. `Both_Shocks`: 1 if both a `Price_Shock` and a `Volume_Shock` occurred on that day, 0 otherwise.

**Reasoning**:
I need to implement the `combine_shock_features` function as outlined in the subtask, apply it to the three dataframes, and then display the head and info of each to verify the new 'Any_Shock' and 'Both_Shocks' columns.
"""

def combine_shock_features(df):
    """
    Combines 'Price_Shock' and 'Volume_Shock' into 'Any_Shock' and 'Both_Shocks' columns.

    Args:
        df (pandas.DataFrame): The input DataFrame with 'Price_Shock' and 'Volume_Shock' columns.

    Returns:
        pandas.DataFrame: The DataFrame with added combined shock columns.
    """
    # Ensure Price_Shock and Volume_Shock columns exist and handle potential NaN values by filling with 0
    df['Price_Shock'] = df['Price_Shock'].fillna(0).astype(int)
    df['Volume_Shock'] = df['Volume_Shock'].fillna(0).astype(int)

    # Create 'Any_Shock' column
    df['Any_Shock'] = ((df['Price_Shock'] == 1) | (df['Volume_Shock'] == 1)).astype(int)

    # Create 'Both_Shocks' column
    df['Both_Shocks'] = ((df['Price_Shock'] == 1) & (df['Volume_Shock'] == 1)).astype(int)

    return df

