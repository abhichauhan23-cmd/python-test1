from datetime import date
from nsepy import get_history
import pandas as pd

def fetch_stock_data(symbol, start_date, end_date, is_index=False):
    """
    Fetches historical stock or index data from NSE using nsepy.

    Args:
        symbol (str): The stock or index symbol (e.g., 'INFY', 'NIFTY IT').
        start_date (datetime.date): The start date for data fetching.
        end_date (datetime.date): The end date for data fetching.
        is_index (bool): True if fetching an index, False if fetching a stock.

    Returns:
        pandas.DataFrame or None: A DataFrame with 'Open', 'Close', 'Low', 'High', 'Volume'
                                  indexed by 'Date', or None if data fetching fails.
    """
    try:
        df = get_history(symbol=symbol, start=start_date, end=end_date, index=is_index)
        if df is None or df.empty:
            raise ValueError("No data returned from nsepy.")

        # Ensure 'Date' is the index and it's sorted
        if 'Date' in df.columns:
            df = df.set_index('Date')
        df.index = pd.to_datetime(df.index)
        df = df.sort_index(ascending=True)

        # Select required columns and rename if necessary (nsepy often returns these)
        required_cols = ['Open', 'Close', 'Low', 'High', 'Volume']
        # Filter to only include columns that exist in the dataframe
        existing_required_cols = [col for col in required_cols if col in df.columns]
        df = df[existing_required_cols]

        print(f"Successfully fetched data for {symbol} from {start_date} to {end_date}.")
        return df
    except Exception as e:
        print(f"Error fetching data for {symbol} from {start_date} to {end_date}: {e}")
        print("Data could not be fetched programmatically. Please manually upload a CSV file with columns: 'Date', 'Open', 'Close', 'Low', 'High', 'Volume'.")
        return None

