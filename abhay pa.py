def calculate_rolling_features(df):
    """
    Calculates rolling mean and standard deviation for 'Close' price and 'Volume'
    for specified periods.

    Args:
        df (pandas.DataFrame): The input DataFrame with 'Close' and 'Volume' columns.

    Returns:
        pandas.DataFrame: The DataFrame with added rolling window feature columns.
    """
    rolling_periods = [10, 75]

    for period in rolling_periods:
        # Rolling mean of 'Close' price
        df[f'RollMean_Close_{period}D'] = df['Close'].rolling(window=period).mean()
        # Rolling standard deviation of 'Close' price
        df[f'RollStd_Close_{period}D'] = df['Close'].rolling(window=period).std()

        # Rolling mean of 'Volume'
        df[f'RollMean_Volume_{period}D'] = df['Volume'].rolling(window=period).mean()
        # Rolling standard deviation of 'Volume'
        df[f'RollStd_Volume_{period}D'] = df['Volume'].rolling(window=period).std()

    return df

