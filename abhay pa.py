def calculate_moving_averages(df):
    """
    Calculates multiple moving averages (4, 16, 26, 39, 52 weeks) on the 'Close' price.
    Assumes 5 trading days per week.

    Args:
        df (pandas.DataFrame): The input DataFrame with a 'Close' price column.

    Returns:
        pandas.DataFrame: The DataFrame with added moving average columns.
    """
    weekly_periods = [4, 16, 26, 39, 52]

    for weeks in weekly_periods:
        trading_days = weeks * 5
        col_name = f'MA_{weeks}W'
        df[col_name] = df['Close'].rolling(window=trading_days).mean()

    return df

